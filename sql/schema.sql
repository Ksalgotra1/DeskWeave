CREATE TABLE IF NOT EXISTS users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('EMPLOYEE', 'ADMIN')),
    department VARCHAR(100) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS workspaces (
    workspace_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    workspace_type VARCHAR(16) NOT NULL CHECK (workspace_type IN ('DESK', 'ROOM')),
    floor INT NOT NULL CHECK (floor >= 1),
    capacity INT NOT NULL CHECK (capacity >= 1),
    has_monitor BOOLEAN NOT NULL DEFAULT FALSE,
    is_standing_desk BOOLEAN NOT NULL DEFAULT FALSE,
    has_projector BOOLEAN NOT NULL DEFAULT FALSE,
    has_whiteboard BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(user_id),
    workspace_id INT NOT NULL REFERENCES workspaces(workspace_id),
    booking_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    attendee_count INT NOT NULL CHECK (attendee_count > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CONFIRMED', 'CHECKED_IN', 'EXPIRED', 'CANCELLED', 'COMPLETED')),
    checked_in_at TIMESTAMP,
    notes VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS booking_audit_log (
    audit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INT NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    actor_user_id INT NOT NULL REFERENCES users(user_id),
    action VARCHAR(32) NOT NULL,
    details TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS capacity_recommendations (
    rec_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    category VARCHAR(32) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    floor INT NOT NULL,
    workspace_type VARCHAR(16) NOT NULL,
    metric_value DOUBLE PRECISION NOT NULL,
    summary TEXT NOT NULL,
    suggested_action TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_bookings_ws_date_status
    ON bookings (workspace_id, booking_date, status);

CREATE INDEX IF NOT EXISTS idx_bookings_date_time
    ON bookings (booking_date, start_time, end_time);

CREATE INDEX IF NOT EXISTS idx_audit_booking_id
    ON booking_audit_log (booking_id);
